const {test,expect}=require('@playwright/test');
const AxeBuilder=require('@axe-core/playwright').default;

test('mobile storefront, filters and accessible product controls',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/');
 await expect(page.getByRole('heading',{name:/Find your everyday blue\.|Blue, made for everyday\./})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 let scan=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
 expect(scan.violations).toEqual([]);
 await page.goto('/products?category=women&sort=price-asc');
 await expect(page.locator('.product-card')).toHaveCount(2);
 await page.locator('.product-image').first().click();
 await expect(page.getByRole('button',{name:'Add to bag',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'S',exact:true}).click();
 await page.getByLabel('Check delivery PIN').fill('111111');
 await page.getByRole('button',{name:'Check',exact:true}).click();
 await expect(page.getByText('Coverage not confirmed for this PIN.')).toBeVisible();
 scan=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
 expect(scan.violations).toEqual([]);
});

