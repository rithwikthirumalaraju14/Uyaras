test('catalog pagination preserves filters and keyboard navigation', async({page})=>{
 await page.goto('/products?page_size=1&sort=price-asc');
 await expect(page.locator('.product-card')).toHaveCount(1);
 await page.getByRole('link',{name:'Next',exact:true}).click();
 await expect(page).toHaveURL(/page=2/);
  await expect(page.getByRole('combobox',{name:'Sort',exact:true})).toHaveValue('price-asc');
 await expect(page.getByRole('navigation',{name:'Product pages'})).toContainText('Page 2');
 await expect(page.getByRole('link',{name:/Wishlist/i})).toHaveCount(0);
 await page.goto('/');
  await expect(page.getByRole('navigation',{name:'Main navigation'})).toBeVisible();
  await page.bringToFront();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('link',{name:'Skip to content'}), await page.evaluate(() => `Keyboard focus: ${document.activeElement?.outerHTML.slice(0,250)}; document focused: ${document.hasFocus()}`)).toBeFocused();
 await page.keyboard.press('Enter');
 await expect(page).toHaveURL(/#main$/);
});

test('staff studio catalog, configuration and audit',async({page})=>{
 const capsule='Test capsule '+Date.now();
 await page.goto('/account');
 await page.getByLabel('Email',{exact:true}).fill('owner@uyaras.test');
 await page.getByLabel('Password',{exact:true}).fill(process.env.UYARAS_TEST_PASSWORD);
 await page.getByRole('button',{name:'Sign in',exact:true}).last().click();
 await expect(page.getByRole('link',{name:'Open staff studio'})).toBeVisible();
 await page.getByRole('link',{name:'Open staff studio'}).click();
 await expect(page.getByRole('heading',{name:'Dashboard',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Categories',exact:true}).click();
 await page.getByLabel('Category name').fill(capsule);
 await page.getByLabel('URL slug',{exact:true}).fill(capsule.toLowerCase().replaceAll(' ','-'));
 await page.getByRole('button',{name:'Save changes'}).click();
 await expect(page.getByRole('cell',{name:capsule,exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await expect(page.getByLabel('Production ordering (locked)')).toBeDisabled();
 await page.getByLabel('Home heading',{exact:true}).fill('Blue, made for everyday.');
 await page.getByRole('button',{name:'Save changes'}).click();
 await expect(page.getByRole('status')).toContainText('Saved.');
 await page.getByRole('button',{name:'Audit',exact:true}).click();
 await expect(page.getByRole('cell',{name:'settings_saved',exact:true}).first()).toBeVisible();
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Blue, made for everyday.'})).toBeVisible();
});
